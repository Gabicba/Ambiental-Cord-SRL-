// Summary for dashboard
export function getMaintenanceSummary() {
  const now = new Date('2026-05-23');
  let expired = 0;
  let due = 0;
  let upcoming = 0;

  maintenanceRecords.forEach((rec) => {
    const dueDate = new Date(rec.next_due_date);
    const daysDiff = Math.floor((dueDate.getTime() - now.getTime()) / (1000 * 60 * 60 * 24));

    if (daysDiff < -7) {
      expired++;
    } else if (daysDiff <= 0) {
      due++;
    } else if (daysDiff <= 30) {
      upcoming++;
    }
  });

  return { expired, due, upcoming, total: maintenanceRecords.length };
}

// Get urgent alerts (Due or Expired)
export function getUrgentAlerts() {
  return maintenanceRecords.filter(
    (rec) => rec.status === 'Due' || rec.status === 'Expired'
  );
}